import sys
sys.stdout.reconfigure(encoding='utf-8')

from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.oxml.ns import qn
from lxml import etree

C_HEADER = RGBColor(0x11, 0x11, 0x11)
C_Q      = RGBColor(0x00, 0x00, 0x00)
C_A      = RGBColor(0x2A, 0x2A, 0x2A)
C_LINE   = RGBColor(0xAA, 0xAA, 0xAA)
FONT     = '游ゴシック'

prs = Presentation()
prs.slide_width  = Inches(13.33)
prs.slide_height = Inches(7.5)
blank = prs.slide_layouts[6]

W     = prs.slide_width
H     = prs.slide_height
MG    = Inches(0.45)
R_END = W - MG
BW    = R_END - MG


def jp(run, name=FONT):
    rPr = run._r.get_or_add_rPr()
    for tag in ('a:latin', 'a:ea', 'a:cs'):
        for el in rPr.findall(qn(tag)):
            rPr.remove(el)
    for tag in ('a:latin', 'a:ea', 'a:cs'):
        el = etree.SubElement(rPr, qn(tag))
        el.set('typeface', name)


def no_shadow(shape):
    try:
        spPr = shape._element.find(qn('p:spPr'))
        if spPr is None:
            return
        for e in spPr.findall(qn('a:effectLst')):
            spPr.remove(e)
        etree.SubElement(spPr, qn('a:effectLst'))
    except Exception:
        pass


def hline(slide, t):
    ln = slide.shapes.add_connector(1, MG, t, R_END, t)
    ln.line.color.rgb = C_LINE
    ln.line.width = Pt(0.9)


def make_slide(category, qa_pairs, page_info=''):
    slide = prs.slides.add_slide(blank)

    # ── ヘッダー ─────────────────────────────────────────
    hb = slide.shapes.add_textbox(MG, Inches(0.18), BW, Inches(0.52))
    tf = hb.text_frame
    p = tf.paragraphs[0]
    r = p.add_run()
    r.text = category + (f'  {page_info}' if page_info else '')
    r.font.size  = Pt(15)
    r.font.bold  = True
    r.font.color.rgb = C_HEADER
    jp(r)
    no_shadow(hb)

    hline(slide, Inches(0.76))

    # ── Q&A 本文 ─────────────────────────────────────────
    cb = slide.shapes.add_textbox(MG, Inches(0.84), BW, Inches(6.5))
    tf = cb.text_frame
    tf.word_wrap = True
    no_shadow(cb)

    first = True
    for q_text, a_text in qa_pairs:
        # Q
        pq = tf.paragraphs[0] if first else tf.add_paragraph()
        if not first:
            pq.space_before = Pt(10)
        rq = pq.add_run()
        rq.text = q_text
        rq.font.size  = Pt(13)
        rq.font.bold  = True
        rq.font.color.rgb = C_Q
        jp(rq)

        # A
        pa = tf.add_paragraph()
        pa.space_before = Pt(2)
        ra = pa.add_run()
        ra.text = a_text
        ra.font.size  = Pt(12)
        ra.font.bold  = False
        ra.font.color.rgb = C_A
        jp(ra)

        first = False


